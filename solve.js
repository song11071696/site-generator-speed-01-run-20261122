// A faster drop-in for makefun-site 1.0.0: run(input) returns exactly the output tree
// makefun-site's build returns for one case's input, byte for byte. Dependency-free,
// no clock, no environment, no randomness, no files: the output is a function of the
// input alone. Written by hand from the reference's rules (its code is the spec).

const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const ESC_RE = /[&<>"']/g;

/** `text` with & < > " and ' escaped. */
function escapeHtml(text) {
  return text.replace(ESC_RE, (c) => ESCAPES[c]);
}

/** The most characters a slug keeps before a collision suffix. */
const SLUG_MAX = 64;

/** Slug cache, reset per run(): titles and tag names repeat. */
let slugCache = null;

function slugifySlow(text) {
  const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
  let out = '';
  let gap = false;
  for (const ch of plain) {
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
  return out === '' ? 'untitled' : out;
}

/**
 * The slug of `text`: NFKD, combining marks dropped, A-Z lowered, every run of
 * characters other than a-z and 0-9 one "-", none at either end, at most 64 characters
 * (a "-" left at the cut dropped), and "untitled" when nothing is left.
 */
function slugify(text) {
  let hit = slugCache.get(text);
  if (hit === undefined) {
    // ASCII fast path: NFKD is the identity on ASCII and ASCII holds no combining marks.
    if (/^[ -~]*$/.test(text)) {
      let s = text.toLowerCase().replace(/[^a-z0-9]+/g, '-');
      if (s.charCodeAt(0) === 45) s = s.slice(1);
      s = s.slice(0, SLUG_MAX);
      if (s.charCodeAt(s.length - 1) === 45) s = s.replace(/-+$/, '');
      hit = s === '' ? 'untitled' : s;
    } else {
      hit = slugifySlow(text);
    }
    slugCache.set(text, hit);
  }
  return hit;
}

/** `slug` made unique against `taken` (and added to it): slug, slug-2, slug-3 ... */
function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** `date` (YYYY-MM-DD) in words, from the string alone: "2026-11-09" is "9 November 2026". */
let longDateCache = null;
function longDate(date) {
  let hit = longDateCache.get(date);
  if (hit === undefined) {
    hit = `${(date.charCodeAt(8) - 48) * 10 + (date.charCodeAt(9) - 48)} ${MONTHS[(date.charCodeAt(5) - 48) * 10 + (date.charCodeAt(6) - 48) - 1]} ${date.slice(0, 4)}`;
    longDateCache.set(date, hit);
  }
  return hit;
}

